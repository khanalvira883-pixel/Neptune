'use client';
import { useState } from 'react';
const D = ['EQ','Critical','Creativity','Memory','Observation','Social','Logic','Language','Focus','Curiosity','Speaking'];
const K: any = { quick: 'Quick question', scenario: 'Scenario', research: 'Research question' };
export default function Lab({ add }: any) {
  const [d, setD] = useState('EQ'), [k, setK] = useState('scenario'), [q, setQ] = useState<any>(null), [a, setA] = useState<number | null>(null), [ld, setLd] = useState(false);
  const go = async () => {
    setLd(true); setA(null);
    try {
      const r = await fetch('/api/generate', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ domain: d, kind: k, uid: localStorage.getItem('uid'), seed: Math.floor(Math.random() * 1e6) }) });
      setQ(await r.json());
    } catch { setQ({ text: 'Could not reach the server. Try again.', options: [], answer: 0, explanation: '', source: 'error' }); }
    setLd(false);
  };
  return <div className="mx-auto max-w-2xl">
    <h3 className="mb-3 text-xl">AI Lab: a fresh challenge every time</h3>
    <div className="mb-3 flex flex-wrap gap-2">
      <select value={d} onChange={(e) => setD(e.target.value)} className="rounded-lg bg-bg2 p-2">{D.map((x) => <option key={x}>{x}</option>)}</select>
      <select value={k} onChange={(e) => setK(e.target.value)} className="rounded-lg bg-bg2 p-2">{Object.keys(K).map((x) => <option key={x} value={x}>{K[x]}</option>)}</select>
      <button onClick={go} className="rounded-full bg-ac px-5 py-2 font-semibold text-bg">{ld ? 'Generating…' : q ? 'Next challenge' : 'Generate'}</button>
    </div>
    {q && <div className="rounded-2xl bg-bg2 p-5">
      <span className="text-xs text-mu">{q.source === 'gpt' ? 'Generated by AI' : 'Built-in question'} · {d}</span>
      <p className="my-3 whitespace-pre-line text-lg">{q.text}</p>
      {q.options.map((o: string, j: number) => <button key={j} disabled={a !== null} onClick={() => { setA(j); add(d, j === q.answer ? 3 : 1); }}
        className={'my-1 block w-full rounded-xl border px-3 py-2 text-left ' + (a === null ? 'border-mu hover:border-ac' : j === q.answer ? 'border-green-400 bg-green-900' : j === a ? 'border-red-400 bg-red-900' : 'border-mu opacity-60')}>{o}</button>)}
      {a !== null && <p className="mt-3 text-sm text-mu">{q.explanation}</p>}
    </div>}
  </div>;
}